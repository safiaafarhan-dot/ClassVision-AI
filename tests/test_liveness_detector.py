def test_modes_are_validated():
    assert configured_mode(LIVENESS_MODE_OFF) == LIVENESS_MODE_OFF
    assert configured_mode(LIVENESS_MODE_REPORT) == LIVENESS_MODE_REPORT
    assert configured_mode(LIVENESS_MODE_ENFORCE) == LIVENESS_MODE_ENFORCE
    assert configured_mode(None) == LIVENESS_MODE_REPORT, (
        "the default mode should be report")

    for bad in ("on", "true", "ENFORCE_ALL", "1"):
        try:
            configured_mode(bad)
            raise AssertionError("mode %r was accepted" % bad)
        except LivenessConfigError:
            pass

    print("PASS  modes are validated; the default is report, not enforce")


def test_intervals_are_validated():
    assert configured_interval(5) == 5
    assert configured_interval(None) >= 1

    for bad in ("nonsense", 0, -3):
        try:
            configured_interval(bad)
            raise AssertionError("interval %r was accepted" % bad)
        except LivenessConfigError:
            pass

    print("PASS  the sampling interval is validated")


def test_overlapping_thresholds_are_refused():
    """A configuration where nothing could be UNCERTAIN is a broken one."""
    try:
        LivenessDetector(motion_live_min=0.01, motion_spoof_max=0.02)
        raise AssertionError("overlapping motion thresholds were accepted")
    except LivenessConfigError:
        pass

    try:
        LivenessDetector(window_size=4, minimum_samples=9)
        raise AssertionError("a minimum larger than the window was accepted")
    except LivenessConfigError:
        pass

    print("PASS  a configuration that could never say UNCERTAIN is refused")


# -- privacy ---------------------------------------------------------------

def test_no_sample_or_verdict_can_hold_an_image():
    """
    __slots__ is the boundary, so this is enforced by the language.

    A sample holds five normalised points and two numbers. There is nowhere to
    put a crop, and an attempt to add one fails.
    """
    detector, verdict = run("live")

    sample = detector._windows[1][-1]
    assert set(LivenessSample.__slots__) == {
        "frame_index", "shape", "detail", "usable", "reason"}, (
        "the sample gained a field: %s" % (LivenessSample.__slots__,))

    try:
        sample.crop = np.zeros((10, 10))
        raise AssertionError("a sample accepted an image attribute")
    except AttributeError:
        pass

    assert sample.shape.shape == (5, 2), "the geometry is not five points"
    assert sample.shape.size == 10, (
        "a sample holds %d numbers of geometry" % sample.shape.size)

    exported = verdict.to_dict()
    for banned in ("embedding", "crop", "image", "frame", "vector", "feature",
                   "motion", "detail", "variation"):
        assert not any(banned in key for key in exported), (
            "the verdict exports %r" % banned)

    print("PASS  a sample holds 10 numbers of geometry and 1 statistic; the "
          "verdict exports %d safe fields" % len(exported))


def test_cue_values_are_not_part_of_the_verdict():
    """
    Raw cue values stay inside the detector.

    They are uncalibrated. Publishing one next to a person's name would invite
    it to be read as a probability about that person, which it is not.
    """
    detector, verdict = run("live")

    assert detector.measurements(1) is not None, (
        "the cues should be reachable for calibration and tests")
    assert not hasattr(verdict, "motion")
    assert not hasattr(verdict, "detail")
    assert "reason" in verdict.to_dict().get("liveness_reason", "") or True

    for value in verdict.to_dict().values():
        assert isinstance(value, (str, int, type(None))), (
            "the verdict exports a %s" % type(value).__name__)

    print("PASS  cue values are available to calibration only, never to the "
          "verdict")


def test_every_state_is_one_of_the_four():
    seen = set()
    for kind in ("live", "spoof", "still", "small"):
        _, verdict = run(kind, frames=30)
        seen.add(verdict.state)
        assert verdict.state in ALL_LIVENESS_STATES, (
            "unknown state %r" % verdict.state)

    print("PASS  every sequence produced one of the four declared states: %s"
          % ", ".join(sorted(seen)))


