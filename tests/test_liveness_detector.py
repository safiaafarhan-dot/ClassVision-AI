"""
Liveness detector tests (Step 9).

NO WEBCAM, NO MODEL AND NO DATASET ARE NEEDED. Every sequence is generated by
ai/liveness_test.py, and its texture statistic was tuned to fall inside the
range measured on this machine's real camera.

WHAT THIS VERIFIES
    That the cues behave as designed, that no single frame can decide
    anything, that UNCERTAIN is produced whenever it should be, and that
    nothing unmeasurable is ever rounded up to LIVE.

WHAT THIS DOES NOT VERIFY
    Anti-spoofing accuracy. These are synthetic sequences, not presentation
    attacks. No real photograph, screen, replayed video or mask has ever been
    shown to this code, and no accuracy, FAR, FRR, APCER, BPCER or ACER is
    claimed anywhere in Step 9.

Run with:
    python tests/test_liveness_detector.py
"""

