def run(kind, frames=40, seed=11, detector=None, track_id=1):
    """Push a synthetic sequence through the detector and return its verdict."""
    detector = detector or LivenessDetector()

    for frame, detection, _ in synthetic_sequence(kind, frames, seed=seed):
        detector.observe(track_id, frame, detection)

    return detector, detector.assess(track_id)


def landmarks_for(box, points=None):
    x, y, width, height = box
    points = points if points is not None else np.array([
        [0.31, 0.36], [0.69, 0.36], [0.50, 0.57],
        [0.35, 0.75], [0.65, 0.75]], dtype=np.float32)
    return np.column_stack([x + points[:, 0] * width,
                            y + points[:, 1] * height]).astype(np.float32)


# -- measurement -----------------------------------------------------------

def test_texture_detail_is_not_a_brightness_rule():
    """
    The detail cue must survive a change in brightness and contrast.

    A cue that moved with the lighting would be measuring how well lit a
    student is, which says nothing about whether they are a photograph.
    """
    rng = np.random.default_rng(3)
    base = rng.normal(120, 20, (120, 120)).astype(np.float32)

    original = texture_detail(base)
    brighter = texture_detail(np.clip(base + 60, 0, 255))
    contrastier = texture_detail(np.clip((base - 120) * 1.8 + 120, 0, 255))

    assert abs(brighter - original) < 0.02 * max(original, 1e-6) + 0.01, (
        "adding 60 to every pixel changed the detail cue from %.4f to %.4f"
        % (original, brighter))
    assert abs(contrastier - original) / max(original, 1e-6) < 0.05, (
        "scaling contrast changed the detail cue from %.4f to %.4f"
        % (original, contrastier))

    print("PASS  the detail cue is invariant to brightness (%.3f -> %.3f) and "
          "contrast (%.3f)" % (original, brighter, contrastier))


def test_texture_detail_falls_when_detail_is_removed():
    rng = np.random.default_rng(5)
    sharp = rng.normal(120, 20, (120, 120)).astype(np.float32)

    blurred = sharp.copy()
    padded = np.pad(blurred, 1, mode="edge")
    blurred = np.stack([
        padded[0:-2, 0:-2], padded[0:-2, 1:-1], padded[0:-2, 2:],
        padded[1:-1, 0:-2], padded[1:-1, 1:-1], padded[1:-1, 2:],
        padded[2:, 0:-2], padded[2:, 1:-1], padded[2:, 2:]]).mean(axis=0)

    assert texture_detail(blurred) < texture_detail(sharp), (
        "removing fine detail did not lower the detail cue")
    print("PASS  removing fine detail lowers the cue (%.3f -> %.3f)"
          % (texture_detail(sharp), texture_detail(blurred)))


def test_normalised_shape_removes_translation_and_scale():
    """
    The cue that carries the decision must ignore rigid movement.

    An attacker waving a photograph produces translation and scale change and
    nothing else. If those survived normalisation, waving a photo would look
    exactly like a living face.
    """
    base = landmarks_for((100, 100, 120, 120))

    moved = base + np.array([57.0, -31.0], dtype=np.float32)
    scaled = base * 1.8
    both = base * 0.6 + np.array([200.0, 40.0], dtype=np.float32)

    reference = normalised_shape(base)

    for name, variant in (("translated", moved), ("scaled", scaled),
                          ("both", both)):
        difference = float(np.max(np.abs(normalised_shape(variant) - reference)))
        assert difference < 1e-4, (
            "a %s copy of the same geometry differed by %.6f" % (name, difference))

    print("PASS  translation and scale are normalised away (max difference "
          "< 1e-4)")


def test_normalised_shape_refuses_degenerate_input():
    for bad in (np.zeros((5, 2), dtype=np.float32),
                np.ones((2, 2), dtype=np.float32)):
        try:
            normalised_shape(bad)
            raise AssertionError("degenerate landmarks were accepted")
        except ValueError:
            pass
    print("PASS  degenerate or too-few landmarks are refused, not guessed at")


# -- verdicts --------------------------------------------------------------

def test_a_live_sequence_is_reported_live():
    detector, verdict = run("live")

    assert verdict.state == LIVENESS_LIVE, (
        "a synthetic live sequence was reported %s (%s)"
        % (verdict.state, verdict.reason))
    assert verdict.baseline_version == BASELINE_VERSION
    assert verdict.usable_observations >= DEFAULT_MINIMUM_SAMPLES
    print("PASS  a deforming, detailed sequence is LIVE - %s" % verdict.reason)


def test_a_static_presented_image_is_reported_spoof():
    """
    A still image, moved rigidly about the frame.

    This is the attack the motion cue models faithfully: a photograph does not
    deform, however much it is waved.
    """
    detector, verdict = run("spoof")

    assert verdict.state == LIVENESS_SPOOF, (
        "a synthetic static presented image was reported %s (%s)"
        % (verdict.state, verdict.reason))
    print("PASS  a rigidly moving still image is SPOOF - %s" % verdict.reason)


def test_a_very_still_real_face_is_uncertain_not_spoof():
    """
    The error that would do the most harm is calling a student a spoof.

    A real person who sits very still is ambiguous, and the honest answer is
    UNCERTAIN. The thresholds are set so that ambiguity lands there.
    """
    detector, verdict = run("still")

    assert verdict.state == LIVENESS_UNCERTAIN, (
        "a barely moving real face was reported %s" % verdict.state)
    print("PASS  a barely moving real face is UNCERTAIN, never SPOOF")


def test_one_frame_can_never_decide_anything():
    detector = LivenessDetector()
    sequence = list(synthetic_sequence("live", 40))

    for index in range(DEFAULT_MINIMUM_SAMPLES - 1):
        frame, detection, _ = sequence[index]
        detector.observe(1, frame, detection)

        verdict = detector.assess(1)
        assert verdict.state == LIVENESS_UNCERTAIN, (
            "a verdict of %s was reached after only %d observations"
            % (verdict.state, index + 1))
        assert "not enough observations" in verdict.reason

    print("PASS  no verdict but UNCERTAIN before %d observations"
          % DEFAULT_MINIMUM_SAMPLES)


def test_an_empty_window_is_uncertain():
    detector = LivenessDetector()
    verdict = detector.assess(99)

    assert verdict.state == LIVENESS_UNCERTAIN
    assert verdict.observations == 0
    print("PASS  a track with no observations is UNCERTAIN, not LIVE")


# -- invalid input ---------------------------------------------------------

def test_a_face_without_landmarks_is_unusable_not_live():
    detector = LivenessDetector()

    for frame, detection, _ in synthetic_sequence("live", 20):
        detection.landmarks = None
        detector.observe(1, frame, detection)

    verdict = detector.assess(1)
    assert verdict.state == LIVENESS_UNCERTAIN
    assert verdict.usable_observations == 0
    assert "unavailable" in verdict.reason
    print("PASS  a face with no landmarks is UNCERTAIN - %s" % verdict.reason)


def test_a_tiny_face_is_unusable_not_live():
    detector, verdict = run("small", frames=20)

    assert verdict.state == LIVENESS_UNCERTAIN
    assert "too small" in verdict.reason
    print("PASS  a face too small to measure is UNCERTAIN - %s" % verdict.reason)


def test_a_broken_frame_never_raises_and_never_becomes_live():
    """
    The failure-safety rule, at the lowest level.

    Whatever is handed in, the detector returns a sample. It never raises into
    the camera worker, and it never produces evidence of life from something it
    could not measure.
    """
    detector = LivenessDetector()
    box = (100, 100, 120, 120)
    detection = Detection(*box, 0.9, landmarks=landmarks_for(box))

    rubbish = [None, "not a frame", 42, np.zeros((0, 0)),
               np.zeros((10, 10, 10, 10)), object()]

    for item in rubbish:
        for _ in range(10):
            sample = detector.observe(1, item, detection)
            assert isinstance(sample, LivenessSample)
            assert not sample.usable, (
                "%r was accepted as a usable measurement" % type(item).__name__)

        verdict = detector.assess(1)
        assert verdict.state == LIVENESS_UNCERTAIN, (
            "%r produced %s" % (type(item).__name__, verdict.state))
        detector.forget(1)

    assert detector.failed_samples == 60
    print("PASS  %d unmeasurable inputs, %d unusable samples, 0 exceptions, "
          "0 LIVE" % (len(rubbish), detector.failed_samples))


def test_a_detection_out_of_bounds_is_handled():
    detector = LivenessDetector()
    frame = np.full((480, 640, 3), 120, dtype=np.uint8)

    box = (625, 465, 200, 200)     # almost entirely outside the frame
    detection = Detection(*box, 0.9, landmarks=landmarks_for(box))

    for _ in range(10):
        detector.observe(1, frame, detection)

    verdict = detector.assess(1)
    assert verdict.state == LIVENESS_UNCERTAIN, (
        "a box almost entirely off-frame produced %s" % verdict.state)
    assert "too small" in verdict.reason
    print("PASS  a box running off the edge of the frame is clipped, then "
          "reported UNCERTAIN")


# -- multiple faces --------------------------------------------------------

def test_two_tracks_are_measured_independently():
    """
    Two people in one frame must not share a window.

    If they did, one person's movement could confirm the other as live, which
    is the single most dangerous kind of bug this layer could have.
    """
    detector = LivenessDetector()

    live_sequence = list(synthetic_sequence("live", 40, seed=11))
    spoof_sequence = list(synthetic_sequence("spoof", 40, seed=11))

    for index in range(40):
        detector.observe(1, live_sequence[index][0], live_sequence[index][1])
        detector.observe(2, spoof_sequence[index][0], spoof_sequence[index][1])

    first = detector.assess(1)
    second = detector.assess(2)

    assert first.state == LIVENESS_LIVE, "track 1 became %s" % first.state
    assert second.state == LIVENESS_SPOOF, "track 2 became %s" % second.state
    assert detector.window_size_for(1) == detector.window_size_for(2)

    print("PASS  in one frame, track 1 is %s and track 2 is %s - separate "
          "windows" % (first.state, second.state))


def test_forgetting_a_track_releases_its_window():
    detector, _ = run("live")

    assert detector.window_size_for(1) > 0
    detector.forget(1)
    assert detector.window_size_for(1) == 0
    assert detector.tracked_ids() == []

    assert detector.assess(1).state == LIVENESS_UNCERTAIN, (
        "a forgotten track should be undecided again, not still LIVE")
    print("PASS  forgetting a track releases its window and its verdict")


def test_pruning_keeps_only_live_tracks():
    detector = LivenessDetector()

    for track_id in (1, 2, 3):
        for frame, detection, _ in list(synthetic_sequence("live", 8)):
            detector.observe(track_id, frame, detection)

    detector.prune([2])
    assert detector.tracked_ids() == [2]
    print("PASS  pruning releases every track the tracker no longer holds")


def test_the_window_is_bounded():
    detector, _ = run("live", frames=200)

    assert detector.window_size_for(1) == detector.window_size, (
        "the window grew to %d" % detector.window_size_for(1))
    print("PASS  a 200-frame track keeps a window of %d, not 200"
          % detector.window_size)


