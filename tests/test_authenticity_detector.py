"""
Authenticity detector tests (Step 10).

NO WEBCAM, NO MODEL AND NO DATASET ARE NEEDED. Every sequence is generated by
ai/authenticity_test.py.

WHAT THIS VERIFIES
    That the cues behave as designed, that no single frame can decide
    anything, that UNCERTAIN is produced whenever it should be, and that
    nothing unmeasurable is ever rounded up to AUTHENTIC.

WHAT THIS DOES NOT VERIFY
    Deepfake detection accuracy. These are synthetic sequences, not
    manipulated video. No face swap, reenactment or replay has ever been
    shown to this code, and no accuracy, FAR, FRR, APCER, BPCER or ACER is
    claimed anywhere in Step 10.

Run with:
    python tests/test_authenticity_detector.py
"""

