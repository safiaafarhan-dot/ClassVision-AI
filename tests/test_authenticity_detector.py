def test_a_tiny_face_is_unusable_not_authentic():
    detector, verdict = run("tiny", frames=80)

    assert verdict.state == AUTHENTICITY_UNCERTAIN
    assert "too small" in verdict.reason
    print("PASS  a face too small to compare is UNCERTAIN - %s" % verdict.reason)


def test_a_face_filling_the_frame_has_no_context():
    detector = AuthenticityDetector()
    frame = np.random.default_rng(1).integers(0, 255, (200, 200, 3),
                                              dtype=np.uint8)
    box = (0, 0, 200, 200)
    detection = Detection(*box, 0.95, landmarks=landmarks_for(box))

    for _ in range(40):
        detector.observe(1, frame, detection)

    verdict = detector.assess(1)
    assert verdict.state == AUTHENTICITY_UNCERTAIN
    assert "context" in verdict.reason
    print("PASS  a face with no surrounding context is UNCERTAIN - %s"
          % verdict.reason)


def test_broken_input_never_raises_and_never_becomes_authentic():
    detector = AuthenticityDetector()
    box = (100, 100, 130, 130)
    detection = Detection(*box, 0.9, landmarks=landmarks_for(box))

    rubbish = [None, "not a frame", 42, np.zeros((0, 0)),
               np.zeros((4, 4, 4, 4)), object()]

    for item in rubbish:
        for _ in range(12):
            sample = detector.observe(1, item, detection)
            assert isinstance(sample, AuthenticitySample)
            assert not sample.usable, (
                "%s was accepted as usable" % type(item).__name__)

        verdict = detector.assess(1)
        assert verdict.state == AUTHENTICITY_UNCERTAIN, (
            "%s produced %s" % (type(item).__name__, verdict.state))
        detector.forget(1)

    assert detector.failed_samples == 12 * len(rubbish)
    print("PASS  %d unmeasurable input kinds, %d unusable samples, 0 "
          "exceptions, 0 AUTHENTIC" % (len(rubbish), detector.failed_samples))


def test_grayscale_input_is_accepted():
    detector = AuthenticityDetector()
    rng = np.random.default_rng(9)
    box = (150, 120, 130, 130)
    detection = Detection(*box, 0.95, landmarks=landmarks_for(box))

    for index in range(80):
        level = 90 + 25 * np.sin(index * 0.4)
        frame = rng.normal(level, 14, (480, 640)).astype(np.float32)
        detector.observe(1, frame, detection)

    verdict = detector.assess(1)
    assert verdict.state in ALL_AUTHENTICITY_STATES
    assert detector.failed_samples == 0, (
        "a grayscale frame was rejected as unmeasurable")
    print("PASS  a 2D grayscale frame is measured without error (verdict %s)"
          % verdict.state)


def test_a_box_off_the_edge_of_the_frame_is_handled():
    detector = AuthenticityDetector()
    frame = np.random.default_rng(2).integers(0, 255, (480, 640, 3),
                                              dtype=np.uint8)
    box = (620, 460, 200, 200)
    detection = Detection(*box, 0.9, landmarks=landmarks_for(box))

    for _ in range(40):
        detector.observe(1, frame, detection)

    assert detector.assess(1).state == AUTHENTICITY_UNCERTAIN
    print("PASS  a box running off the frame is clipped, then UNCERTAIN")


# -- multiple tracks -------------------------------------------------------

def test_two_tracks_are_measured_independently():
    detector = AuthenticityDetector()
    coupled = list(synthetic_sequence("coupled", FRAMES, seed=17))
    inverted = list(synthetic_sequence("inverted", FRAMES, seed=17))

    for index in range(FRAMES):
        detector.observe(1, coupled[index][0], coupled[index][1])
        detector.observe(2, inverted[index][0], inverted[index][1])

    first = detector.assess(1)
    second = detector.assess(2)

    assert first.state == AUTHENTICITY_AUTHENTIC, "track 1 became %s" % first.state
    assert second.state == AUTHENTICITY_SUSPICIOUS, (
        "track 2 became %s" % second.state)

    print("PASS  in one frame, track 1 is %s and track 2 is %s - separate "
          "windows" % (first.state, second.state))


def test_forgetting_a_track_releases_its_window():
    detector, _ = run("coupled")

    assert detector.window_size_for(1) > 0
    detector.forget(1)
    assert detector.window_size_for(1) == 0
    assert detector.tracked_ids() == []
    assert detector.assess(1).state == AUTHENTICITY_UNCERTAIN
    print("PASS  forgetting a track releases its window and its verdict")


def test_pruning_keeps_only_live_tracks():
    detector = AuthenticityDetector()
    for track_id in (1, 2, 3):
        for frame, detection, _ in list(synthetic_sequence("coupled", 10)):
            detector.observe(track_id, frame, detection)

    detector.prune([2])
    assert detector.tracked_ids() == [2]
    print("PASS  pruning releases every track the tracker no longer holds")


def test_the_window_is_bounded():
    detector, _ = run("coupled", frames=400)

    assert detector.window_size_for(1) == detector.window_size, (
        "the window grew to %d" % detector.window_size_for(1))
    print("PASS  a 400-frame track keeps a window of %d, not 400"
          % detector.window_size)


# -- configuration ---------------------------------------------------------

def test_modes_are_validated_and_default_to_off():
    assert configured_mode(AUTHENTICITY_MODE_OFF) == AUTHENTICITY_MODE_OFF
    assert configured_mode(AUTHENTICITY_MODE_REPORT) == AUTHENTICITY_MODE_REPORT
    assert configured_mode(AUTHENTICITY_MODE_ENFORCE) == AUTHENTICITY_MODE_ENFORCE

    assert configured_mode(None) == AUTHENTICITY_MODE_OFF, (
        "Step 10 must default to OFF so it cannot change what Step 9's "
        "eligibility column means")

    for bad in ("on", "true", "1", "ENFORCE_ALL"):
        try:
            configured_mode(bad)
            raise AssertionError("mode %r was accepted" % bad)
        except AuthenticityConfigError:
            pass

    print("PASS  modes are validated; the default is off, not report")


def test_intervals_are_validated():
    assert configured_interval(6) == 6
    assert configured_interval(None) >= 1

    for bad in ("nonsense", 0, -2):
        try:
            configured_interval(bad)
            raise AssertionError("interval %r was accepted" % bad)
        except AuthenticityConfigError:
            pass

    print("PASS  the sampling interval is validated, including 0")


def test_overlapping_thresholds_are_refused():
    for kwargs in ({"coupling_authentic_min": 0.1,
                    "coupling_suspicious_max": 0.2},
                   {"sharpness_authentic_min": 0.05,
                    "sharpness_suspicious_max": 0.5},
                   {"window_size": 10, "minimum_samples": 40}):
        try:
            AuthenticityDetector(**kwargs)
            raise AssertionError("accepted %s" % kwargs)
        except AuthenticityConfigError:
            pass

    print("PASS  a configuration that could never say UNCERTAIN is refused")


def test_the_detector_describes_itself_honestly():
    described = AuthenticityDetector().describe()

    assert described["baseline"] == BASELINE_NAME
    assert described["model"] is None, "a model was claimed where none exists"
    assert described["trained"] is False
    assert described["evaluated"] is False

    print("PASS  the detector reports model=None, trained=False, "
          "evaluated=False")


# -- privacy ---------------------------------------------------------------

def test_no_sample_or_verdict_can_hold_an_image():
    detector, verdict = run("coupled")

    assert set(AuthenticitySample.__slots__) == {
        "frame_index", "face_detail", "context_detail", "face_luma",
        "context_luma", "chroma_offset", "usable", "reason"}, (
        "the sample gained a field: %s" % (AuthenticitySample.__slots__,))

    sample = detector._windows[1][-1]
    try:
        sample.crop = np.zeros((10, 10))
        raise AssertionError("a sample accepted an image attribute")
    except AttributeError:
        pass

    for slot in AuthenticitySample.__slots__:
        value = getattr(sample, slot)
        assert not isinstance(value, np.ndarray), (
            "%s holds an array" % slot)

    exported = verdict.to_dict()
    for banned in ("embedding", "crop", "image", "frame", "vector", "feature",
                   "coupling", "sharpness", "chroma", "luma"):
        assert not any(banned in key for key in exported), (
            "the verdict exports %r" % banned)

    print("PASS  a sample holds 6 numbers and 2 flags; the verdict exports %d "
          "safe fields" % len(exported))


def test_cue_values_are_not_part_of_the_verdict():
    detector, verdict = run("coupled")

    assert detector.measurements(1) is not None, (
        "the cues should be reachable for calibration and tests")
    for attribute in ("coupling", "sharpness_ratio", "chroma_offset"):
        assert not hasattr(verdict, attribute)

    for value in verdict.to_dict().values():
        assert isinstance(value, (str, int, type(None))), (
            "the verdict exports a %s" % type(value).__name__)

    print("PASS  cue values reach calibration only, never the verdict")


def test_every_state_is_one_of_the_four():
    seen = set()
    for kind in ("coupled", "decoupled", "inverted", "smooth", "tiny"):
        _, verdict = run(kind, frames=120)
        seen.add(verdict.state)
        assert verdict.state in ALL_AUTHENTICITY_STATES, (
            "unknown state %r" % verdict.state)

    print("PASS  every sequence produced one of the four declared states: %s"
          % ", ".join(sorted(seen)))


