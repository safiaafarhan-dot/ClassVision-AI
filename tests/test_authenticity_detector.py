# Long enough to clear the 60-sample minimum comfortably.
FRAMES = 200


def run(kind, frames=FRAMES, seed=17, detector=None, track_id=1):
    detector = detector or AuthenticityDetector()
    for frame, detection, _ in synthetic_sequence(kind, frames, seed=seed):
        detector.observe(track_id, frame, detection)
    return detector, detector.assess(track_id)


def landmarks_for(box):
    x, y, width, height = box
    points = np.array([[0.31, 0.36], [0.69, 0.36], [0.50, 0.57],
                       [0.35, 0.75], [0.65, 0.75]], dtype=np.float32)
    return np.column_stack([x + points[:, 0] * width,
                            y + points[:, 1] * height]).astype(np.float32)


# -- measurement -----------------------------------------------------------

def test_detail_energy_is_not_a_brightness_rule():
    rng = np.random.default_rng(3)
    base = rng.normal(120, 20, (120, 120)).astype(np.float32)

    original = detail_energy(base)
    brighter = detail_energy(np.clip(base + 60, 0, 255))
    contrastier = detail_energy(np.clip((base - 120) * 1.8 + 120, 0, 255))

    assert abs(brighter - original) / max(original, 1e-6) < 0.05, (
        "adding 60 to every pixel changed the cue from %.4f to %.4f"
        % (original, brighter))
    assert abs(contrastier - original) / max(original, 1e-6) < 0.05

    print("PASS  the detail cue survives brightness (%.3f -> %.3f) and "
          "contrast (%.3f)" % (original, brighter, contrastier))


def test_detail_energy_handles_degenerate_regions():
    assert detail_energy(np.zeros((0, 0), dtype=np.float32)) == 0.0
    assert detail_energy(np.zeros((2, 2), dtype=np.float32)) == 0.0
    assert detail_energy(np.full((40, 40), 130.0, dtype=np.float32)) == 0.0
    print("PASS  empty, tiny and perfectly flat regions return 0, not an error")


# -- verdicts --------------------------------------------------------------

def test_a_coupled_sequence_is_reported_authentic():
    detector, verdict = run("coupled")

    assert verdict.state == AUTHENTICITY_AUTHENTIC, (
        "a coupled sequence was reported %s (%s)"
        % (verdict.state, verdict.reason))
    assert verdict.baseline_version == BASELINE_VERSION
    assert verdict.usable_observations >= DEFAULT_MINIMUM_SAMPLES
    print("PASS  a face that changes with its surroundings is AUTHENTIC - %s"
          % verdict.reason)


def test_an_inverted_sequence_is_reported_suspicious():
    """
    The only case the coupling cue can actually catch.

    A face whose brightness moves OPPOSITE to its surroundings is not
    something one camera produces.
    """
    detector, verdict = run("inverted")

    assert verdict.state == AUTHENTICITY_SUSPICIOUS, (
        "an inverted sequence was reported %s (%s)"
        % (verdict.state, verdict.reason))
    print("PASS  a face moving opposite to its surroundings is SUSPICIOUS - %s"
          % verdict.reason)


def test_a_merely_decoupled_sequence_is_uncertain_not_suspicious():
    """
    The limitation, asserted rather than described.

    An independently-driven face region sits near zero correlation - and so
    does a real face in a static, evenly lit room. The thresholds refuse to
    separate them, on purpose: flagging still students would be the worse
    error.
    """
    detector, verdict = run("decoupled")

    assert verdict.state == AUTHENTICITY_UNCERTAIN, (
        "a merely decoupled sequence was reported %s - the suspicious "
        "threshold has been moved up into the range where real static scenes "
        "also live" % verdict.state)
    print("PASS  a merely decoupled face is UNCERTAIN, never SUSPICIOUS")


def test_a_smooth_but_coupled_face_is_uncertain():
    """
    Texture alone may not decide anything.

    A softly lit or slightly out-of-focus student is smooth, and a texture cue
    left to decide on its own would call them suspicious.
    """
    detector, verdict = run("smooth")

    assert verdict.state == AUTHENTICITY_UNCERTAIN, (
        "a smooth but coupled face was reported %s" % verdict.state)
    print("PASS  a smooth but properly coupled face is UNCERTAIN, never "
          "SUSPICIOUS")


def test_no_single_frame_can_decide_anything():
    detector = AuthenticityDetector()
    sequence = list(synthetic_sequence("coupled", FRAMES))

    for index in range(DEFAULT_MINIMUM_SAMPLES - 1):
        frame, detection, _ = sequence[index]
        detector.observe(1, frame, detection)

        verdict = detector.assess(1)
        assert verdict.state == AUTHENTICITY_UNCERTAIN, (
            "a verdict of %s was reached after only %d observations"
            % (verdict.state, index + 1))

    assert REASON_INSUFFICIENT_EVIDENCE in detector.assess(1).reason
    print("PASS  no verdict but UNCERTAIN before %d observations, and the "
          "reason says %s" % (DEFAULT_MINIMUM_SAMPLES,
                              REASON_INSUFFICIENT_EVIDENCE))


def test_an_empty_window_is_uncertain():
    detector = AuthenticityDetector()
    verdict = detector.assess(404)

    assert verdict.state == AUTHENTICITY_UNCERTAIN
    assert verdict.observations == 0
    print("PASS  a track with no observations is UNCERTAIN, not AUTHENTIC")


def test_a_static_scene_cannot_be_decided():
    """
    Nothing moved, so there is nothing to correlate.

    Reporting a verdict from a zero-variance series would be noise amplified
    into a claim about a person.
    """
    detector = AuthenticityDetector()
    frame = np.full((480, 640, 3), 120, dtype=np.uint8)
    frame[170:300, 250:380] = 160
    box = (250, 170, 130, 130)
    detection = Detection(*box, 0.95, landmarks=landmarks_for(box))

    for _ in range(FRAMES):
        detector.observe(1, frame, detection)

    verdict = detector.assess(1)
    assert verdict.state == AUTHENTICITY_UNCERTAIN, (
        "a perfectly static scene produced %s" % verdict.state)
    print("PASS  an unchanging scene is UNCERTAIN - %s" % verdict.reason)


